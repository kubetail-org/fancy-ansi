import { compile } from '@tailwindcss/node';

import * as colors from './colors';
import plugin from './plugin';

// Vitest doesn't inline const enums, so `StandardColorKeys` is exported at runtime too
const palettes = Object.entries(colors).filter(([, value]) => 'black' in value);

function generate() {
  const blocks = palettes.map(([name, palette]) => {
    const keys = Object.keys(palette);
    const theme = keys.map((key) => `  --ansi-${name}-${key}: ${palette[key as keyof typeof palette]};`);
    const utility = keys.map((key) => `  --ansi-${key}: var(--ansi-${name}-${key});`);
    return [
      `@theme {\n${theme.join('\n')}\n}`,
      `@utility ansi-${name} {\n${utility.join('\n')}\n}`,
    ].join('\n\n');
  });

  return [
    '/* Generated by src/plugin.test.ts from src/colors.ts. Update with `pnpm test run -u`. */',
    ...blocks,
  ].join('\n\n') + '\n';
}

describe('plugin.css', () => {
  it('matches the palettes in colors.ts', async () => {
    await expect(generate()).toMatchFileSnapshot('./plugin.css');
  });

  it('compiles to palette utilities', async () => {
    const input = [
      '@import "tailwindcss";',
      '@custom-variant dark (&:where(.dark, .dark *));',
      generate(),
    ].join('\n');
    const compiler = await compile(input, { base: __dirname, onDependency: () => {} });
    const output = compiler.build(['ansi-vscode', 'dark:ansi-xtermjs']);

    expect(output).toContain(`--ansi-vscode-red: ${colors.vscode.red};`);
    expect(output).toMatch(/\.ansi-vscode \{\s+--ansi-black: var\(--ansi-vscode-black\);/);
    expect(output).toMatch(/\.dark\\:ansi-xtermjs:where\(\.dark, \.dark \*\) \{\s+--ansi-black: var\(--ansi-xtermjs-black\);/);
  });
});

describe('plugin.ts', () => {
  it('exposes the palettes in the theme', () => {
    expect(plugin.config.theme.ansi.colors.vscode).toEqual(colors.vscode);
  });
});
